  /**
   * 根据本年发生的事，给出一段定调的开场白。
   * 让一卷年报读起来像一章书，而不是一列日志。
   */
  function prelude(moment, entries) {
    const k = {};
    for (const e of entries) k[e.kind] = (k[e.kind] || 0) + 1;

    const bad = (k.danger || 0) + (k.conflict || 0);
    const good = (k.breakthrough || 0) + (k.fortune || 0) + (k.loot || 0);
    const quiet = bad === 0 && good <= 1;
    const m = moment;

    if (bad >= 3) {
      return U.pick([
        `这一年不太平。${m.weather}的夜里，山上好几次亮起了灯。`,
        `${m.season}的山风一直没停。有些事，这一年之内没能收住。`,
        `出了几桩事。有的事后来查清了，有的没有。`,
      ]);
    }
    if (bad > 0) {
      return U.pick([
        `${m.weather}，${m.hour}。宗门里出了点岔子，好在没有闹大。`,
        `这一年总体来说还行，只有一件事让人心里不踏实。`,
        `${m.season}，山上比往常热闹些——不全是好事。`,
      ]);
    }
    if (good >= 2) {
      return U.pick([
        `这一年有了起色。${m.weather}，山上的气机都活泛起来了。`,
        `${m.season}。弟子们比平时勤快，连着几天，后山的灯都亮到很晚。`,
        `好事成双。这一年，宗门上下都轻快了不少。`,
      ]);
    }
    if (quiet) {
      return U.pick([
        `${m.season}，${m.weather}。山门紧闭，这一年没人来，也没人出去。`,
        `雾从后山漫上来，一整年都没散。宗门里安静得能听见煮茶的声音。`,
        `${m.hour}之后，山上就只剩风声了。弟子们照旧打坐、抄书、睡觉。`,
        `日子照旧。${m.weather}，山门，几房，几口人。`,
      ]);
    }
    return U.pick([
      `${m.season}，${m.weather}。日子照旧，只是各有各的忙。`,
      `这一年没什么大事。若真要记，也就那么几桩。`,
      `${m.hour}，山上起了点风。有人下山，有人上山。`,
    ]);
  }

